// The page's content as Markdown, ready to paste into a PR description.
// Diagrams are Mermaid, which GitHub and GitLab render inline.

const INTENT_ICON = { matches: '✅', partial: '🟡', mismatch: '❌', unchecked: '❔', unstated: '➖' }
const CHANGE_ICON = { added: '🟢 added', removed: '🔴 removed', changed: '🟠 changed' }
const CONV_ICON = { follows: '✅ follows', departs: '⚠️ departs', new: '🆕 new pattern' }

const mid = (s) => 'n_' + String(s).replace(/[^A-Za-z0-9_]/g, '_')
const mlabel = (s) => String(s ?? '').replace(/"/g, "'").replace(/[\n\r]+/g, ' ').replace(/[<>]/g, '')
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ')

export function toMarkdown(d) {
  const out = []
  const m = d.meta
  const head = m.number ? `${m.repo} #${m.number}` : `${m.repo}${m.branch ? ` · ${m.branch}` : ''}`
  out.push(`## What this ${m.number ? 'PR' : 'change'} does`, '')
  out.push(`**${d.summary}**`, '')
  if (d.overview) out.push(d.overview, '')
  const facts = [`${head}`, `${m.files} files`, `+${m.add} −${m.del}`]
  if (d.effort) facts.push(`effort ${d.effort.score}/5`)
  out.push(`<sub>${facts.join(' · ')}</sub>`, '')

  if (d.intent?.checks?.length) {
    out.push(`### Intent vs code${d.intent.source ? ` <sub>(from ${d.intent.source})</sub>` : ''}`, '')
    out.push('| | Claim | Note |', '|---|---|---|')
    for (const c of d.intent.checks) out.push(`| ${INTENT_ICON[c.status] || ''} | ${cell(c.claim)} | ${cell(c.note)} |`)
    out.push('')
  }

  const a = d.architecture
  if (a) {
    out.push('### Architecture impact', '')
    if (a.summary) out.push(a.summary, '')
    for (const i of a.impact) out.push(`- **${CHANGE_ICON[i.change] || i.change} ${i.kind}:** ${i.title}${i.detail ? ` — ${i.detail}` : ''}`)
    if (a.impact.length) out.push('')
    if (a.diagram) out.push('```mermaid', archMermaid(a.diagram), '```', '')
    if (a.conventions.length) {
      out.push('| Convention | Source | Status | Note |', '|---|---|---|---|')
      for (const c of a.conventions) out.push(`| ${cell(c.rule)} | ${cell(c.source)} | ${CONV_ICON[c.status] || c.status} | ${cell(c.note)} |`)
      out.push('')
    }
  }

  for (const f of d.flows) {
    out.push(`### Flow: ${f.title}`, '')
    if (f.description) out.push(f.description, '')
    for (const c of f.cases) {
      if (f.cases.length > 1) out.push(`**${c.label}**${c.outcome ? ` — ${c.outcome}` : ''}`, '')
      else if (c.outcome) out.push(c.outcome, '')
      if (Array.isArray(c.before) && c.before.length) {
        out.push('<details><summary>Before this change</summary>', '', '```mermaid', seqMermaid(f, c.before, c.after, 'before'), '```', '</details>', '')
      }
      out.push('```mermaid', seqMermaid(f, c.after, c.before, 'after'), '```', '')
    }
  }

  if (d.decisions.length) {
    out.push('### Decisions made', '')
    for (const x of d.decisions) {
      const chose = x.chose ? ` Chose ${x.chose}${x.over ? ` over ${x.over}` : ''}.` : ''
      out.push(`- **${x.title}.**${chose} ${x.why || ''}${x.where?.length ? ` <sub>${x.where.map((w) => '`' + w + '`').join(', ')}</sub>` : ''}`)
    }
    out.push('')
  }

  if (d.attention.length) {
    out.push('### Worth a closer look', '')
    for (const x of d.attention) out.push(`- **[${x.tag}] ${x.title}** — ${x.why || ''}${x.step ? ` _(step ${x.step})_` : ''}`)
    out.push('')
  }

  out.push('### Walkthrough', '')
  out.push('| Step | What | Files |', '|---|---|---|')
  for (const s of d.steps) out.push(`| ${s.n} | **${cell(s.title)}** — ${cell(s.why)} | ${s.files.map((f) => '`' + f.path + '`').join('<br>')} |`)
  out.push('')

  if (d.stopped.length) {
    out.push('### What stopped happening', '')
    for (const s of d.stopped) out.push(`- ${s.what}${s.why ? ` — ${s.why}` : ''}${s.where ? ` <sub>\`${s.where}\`</sub>` : ''}`)
    out.push('')
  }
  if (d.skip.length) {
    out.push('<details><summary>Files you can skip</summary>', '')
    for (const g of d.skip) out.push(`- **${g.kind}**${g.why ? ` — ${g.why}` : ''}: ${g.files.map((f) => '`' + f.path + '`').join(', ')}`)
    out.push('', '</details>', '')
  }
  if (d.unchecked.length) {
    out.push('<details><summary>Not verified (needs running the code)</summary>', '')
    for (const u of d.unchecked) out.push(`- ${u}`)
    out.push('', '</details>', '')
  }
  out.push(`<sub>Generated by [explain-pr](https://github.com/rodriguesnavil/explain-pr)${m.head?.sha ? ` at ${String(m.head.sha).slice(0, 7)}` : ''}.</sub>`, '')
  return out.join('\n')
}

export function archMermaid(dia) {
  const lines = ['flowchart TD']
  const byLayer = new Map()
  for (const n of dia.nodes) {
    const k = n.layer ?? ''
    if (!byLayer.has(k)) byLayer.set(k, [])
    byLayer.get(k).push(n)
  }
  const node = (n) => {
    const label = mlabel(n.label) + (n.status && n.status !== 'same' ? ` (${n.status})` : '')
    const shape = n.kind === 'db' || n.kind === 'store' ? [`[("`, `")]`] : n.kind === 'external' ? [`{{"`, `"}}`] : n.kind === 'queue' ? [`[/"`, `"/]`] : [`["`, `"]`]
    return `${mid(n.id)}${shape[0]}${label}${shape[1]}`
  }
  const layers = dia.layers || []
  for (const [k, nodes] of byLayer) {
    const layer = layers.find((l) => l.id === k)
    if (k !== '' && layer) {
      lines.push(`  subgraph ${mid('layer_' + k)}["${mlabel(layer.label)}"]`)
      for (const n of nodes) lines.push('    ' + node(n))
      lines.push('  end')
    } else for (const n of nodes) lines.push('  ' + node(n))
  }
  const linkStyles = []
  ;(dia.edges || []).forEach((e, i) => {
    const arrow = e.status === 'removed' ? '-.->' : '-->'
    lines.push(`  ${mid(e.from)} ${arrow}${e.label ? `|"${mlabel(e.label)}"|` : ''} ${mid(e.to)}`)
    if (e.status === 'added') linkStyles.push(`  linkStyle ${i} stroke:#16a34a,stroke-width:2px`)
    if (e.status === 'removed') linkStyles.push(`  linkStyle ${i} stroke:#dc2626,stroke-dasharray:4 4`)
    if (e.status === 'changed') linkStyles.push(`  linkStyle ${i} stroke:#d97706,stroke-width:2px`)
  })
  lines.push(...linkStyles)
  lines.push('  classDef added fill:#dcfce7,stroke:#16a34a,color:#14532d')
  lines.push('  classDef removed fill:#fee2e2,stroke:#dc2626,color:#7f1d1d,stroke-dasharray:4 4')
  lines.push('  classDef changed fill:#fef3c7,stroke:#d97706,color:#78350f')
  for (const s of ['added', 'removed', 'changed']) {
    const ids = dia.nodes.filter((n) => n.status === s).map((n) => mid(n.id))
    if (ids.length) lines.push(`  class ${ids.join(',')} ${s}`)
  }
  return lines.join('\n')
}

const msgKey = (m) => `${m.from}|${m.to}|${m.text}`

export function seqMermaid(flow, msgs, other, side) {
  const lines = ['sequenceDiagram']
  for (const p of flow.participants) lines.push(`  participant ${mid(p.id)} as ${mlabel(p.label || p.id)}`)
  const otherKeys = new Set((other || []).map(msgKey))
  for (const m of msgs || []) {
    const arrow = m.reply ? '-->>' : '->>'
    let tag = ''
    const change = m.change || (Array.isArray(other) && !otherKeys.has(msgKey(m)) ? (side === 'after' ? 'new' : 'gone') : null)
    if (change === 'new') tag = ' 🆕'
    else if (change === 'gone') tag = ' ✖'
    else if (change === 'changed') tag = ' ✎'
    const text = mlabel(m.text).replace(/[;#]/g, ' ') + tag + (m.error ? ' ⚠' : '')
    lines.push(`  ${mid(m.from)}${arrow}${mid(m.to)}: ${text}`)
    if (m.note) lines.push(`  Note over ${mid(m.to)}: ${mlabel(m.note).replace(/[;#]/g, ' ')}`)
  }
  return lines.join('\n')
}
